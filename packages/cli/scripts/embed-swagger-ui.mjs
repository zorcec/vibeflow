#!/usr/bin/env node
/**
 * Vendors the Swagger UI browser assets into src/server/swagger-ui.gen.ts.
 *
 * The docs viewer (GET /api/docs) must work offline with no CDN, so the two
 * files the viewer needs — swagger-ui-bundle.js and swagger-ui.css from the
 * swagger-ui-dist npm package (devDependency) — are embedded as string
 * constants, following the kanban-bundle.gen.ts / openapi.gen.ts pattern.
 * Only these two files are served; the standalone preset, oauth redirect
 * page and source maps stay out of the bundle.
 *
 * Deterministic: re-running emits byte-identical output for the same
 * installed swagger-ui-dist version. Run automatically via the "prebuild"
 * npm script; the output is checked in.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const cliRoot = join(here, "..");
const require = createRequire(join(cliRoot, "package.json"));

const distDir = dirname(require.resolve("swagger-ui-dist/package.json"));
const pkg = JSON.parse(
  readFileSync(join(distDir, "package.json"), "utf-8"),
);

const bundleJs = readFileSync(join(distDir, "swagger-ui-bundle.js"), "utf-8");
const bundleCss = readFileSync(join(distDir, "swagger-ui.css"), "utf-8");

const out = `// AUTO-GENERATED by scripts/embed-swagger-ui.mjs — do not edit.
// Vendored from swagger-ui-dist@${pkg.version} (Apache-2.0, © SmartBear Software;
// see node_modules/swagger-ui-dist/LICENSE). Served verbatim by GET /api/docs
// so the API docs viewer works offline with no CDN. Re-run 'npm run build'
// (prebuild) to regenerate after a swagger-ui-dist upgrade.
/** swagger-ui-dist version these assets were vendored from. */
export const SWAGGER_UI_VERSION = ${JSON.stringify(pkg.version)};
/** swagger-ui-bundle.js (BaseLayout + apis preset; no standalone preset). */
export const SWAGGER_UI_BUNDLE_JS: string = ${JSON.stringify(bundleJs)};
/** swagger-ui.css. */
export const SWAGGER_UI_CSS: string = ${JSON.stringify(bundleCss)};
`;

const genTs = join(cliRoot, "src", "server", "swagger-ui.gen.ts");
writeFileSync(genTs, out);
console.log(
  `[embed-swagger-ui] Vendored swagger-ui-dist@${pkg.version} ` +
    `(js ${bundleJs.length}B, css ${bundleCss.length}B) into src/server/swagger-ui.gen.ts`,
);
